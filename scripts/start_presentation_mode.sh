#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MODE="${1:-mapping}"

export BUDDYBOT_PREFLIGHT_CHECK="${BUDDYBOT_PREFLIGHT_CHECK:-0}"
export BUDDYBOT_ENABLE_MIC_LISTENER="${BUDDYBOT_ENABLE_MIC_LISTENER:-1}"
export BUDDYBOT_ENABLE_PI_SPEAKER="${BUDDYBOT_ENABLE_PI_SPEAKER:-1}"
export BUDDYBOT_SPEAKER_VOLUME_PERCENT="${BUDDYBOT_SPEAKER_VOLUME_PERCENT:-35}"
export BUDDYBOT_CAMERA_WIDTH="${BUDDYBOT_CAMERA_WIDTH:-320}"
export BUDDYBOT_CAMERA_HEIGHT="${BUDDYBOT_CAMERA_HEIGHT:-240}"
export BUDDYBOT_CAMERA_FPS="${BUDDYBOT_CAMERA_FPS:-10}"
export BUDDYBOT_CAMERA_PUBLISH_RATE="${BUDDYBOT_CAMERA_PUBLISH_RATE:-10}"
export BUDDYBOT_CAMERA_START_DELAY="${BUDDYBOT_CAMERA_START_DELAY:-10}"
export BUDDYBOT_LIDAR_SETTLE_DELAY="${BUDDYBOT_LIDAR_SETTLE_DELAY:-10}"
export BUDDYBOT_CAMERA_PIXEL_FORMAT="${BUDDYBOT_CAMERA_PIXEL_FORMAT:-MJPG}"
export BUDDYBOT_CAMERA_BUFFER_SIZE="${BUDDYBOT_CAMERA_BUFFER_SIZE:-1}"
export BUDDYBOT_CAMERA_DISCARD_BUFFERED_FRAMES="${BUDDYBOT_CAMERA_DISCARD_BUFFERED_FRAMES:-2}"
export BUDDYBOT_DETECT_INTERVAL="${BUDDYBOT_DETECT_INTERVAL:-2}"
export BUDDYBOT_DETECT_CONFIDENCE="${BUDDYBOT_DETECT_CONFIDENCE:-0.2}"
export BUDDYBOT_DETECT_PUBLISH_DEBUG="${BUDDYBOT_DETECT_PUBLISH_DEBUG:-1}"
export BUDDYBOT_DETECT_HOG_CONFIDENCE="${BUDDYBOT_DETECT_HOG_CONFIDENCE:-0.08}"
export BUDDYBOT_DETECT_HOG_RESIZE_WIDTH="${BUDDYBOT_DETECT_HOG_RESIZE_WIDTH:-320}"
export BUDDYBOT_DETECT_ALLOW_HOG_FALLBACK="${BUDDYBOT_DETECT_ALLOW_HOG_FALLBACK:-1}"
export BUDDYBOT_DETECT_ALLOW_CASCADE_FALLBACK="${BUDDYBOT_DETECT_ALLOW_CASCADE_FALLBACK:-1}"
export BUDDYBOT_FOLLOW_BBOX_TIMEOUT="${BUDDYBOT_FOLLOW_BBOX_TIMEOUT:-0.6}"
export BUDDYBOT_FOLLOW_MAX_SOURCE_AGE="${BUDDYBOT_FOLLOW_MAX_SOURCE_AGE:-0.8}"
export BUDDYBOT_FOLLOW_HEIGHT_GAIN="${BUDDYBOT_FOLLOW_HEIGHT_GAIN:-0.0035}"
export BUDDYBOT_FOLLOW_CENTER_GAIN="${BUDDYBOT_FOLLOW_CENTER_GAIN:-0.0012}"
export BUDDYBOT_FOLLOW_TARGET_HEIGHT="${BUDDYBOT_FOLLOW_TARGET_HEIGHT:-0.50}"
export BUDDYBOT_FOLLOW_MAX_LINEAR="${BUDDYBOT_FOLLOW_MAX_LINEAR:-0.16}"
export BUDDYBOT_FOLLOW_MAX_ANGULAR="${BUDDYBOT_FOLLOW_MAX_ANGULAR:-0.10}"
export BUDDYBOT_FOLLOW_MIN_LINEAR="${BUDDYBOT_FOLLOW_MIN_LINEAR:-0.10}"
export BUDDYBOT_FOLLOW_COMMAND_RATE="${BUDDYBOT_FOLLOW_COMMAND_RATE:-10.0}"
export BUDDYBOT_FOLLOW_LINEAR_ACCEL="${BUDDYBOT_FOLLOW_LINEAR_ACCEL:-0.12}"
export BUDDYBOT_FOLLOW_ANGULAR_ACCEL="${BUDDYBOT_FOLLOW_ANGULAR_ACCEL:-0.12}"
export BUDDYBOT_FOLLOW_BBOX_SMOOTHING_ALPHA="${BUDDYBOT_FOLLOW_BBOX_SMOOTHING_ALPHA:-0.25}"
export BUDDYBOT_FOLLOW_BBOX_FILTER_RESET_SEC="${BUDDYBOT_FOLLOW_BBOX_FILTER_RESET_SEC:-0.9}"
export BUDDYBOT_FOLLOW_CENTER_DEADZONE="${BUDDYBOT_FOLLOW_CENTER_DEADZONE:-50}"
export BUDDYBOT_FOLLOW_HEIGHT_DEADZONE="${BUDDYBOT_FOLLOW_HEIGHT_DEADZONE:-30}"
export BUDDYBOT_FOLLOW_ALLOW_REVERSE="${BUDDYBOT_FOLLOW_ALLOW_REVERSE:-0}"

echo "[presentation] mode: $MODE"
echo "[presentation] preflight: $BUDDYBOT_PREFLIGHT_CHECK"
echo "[presentation] microphone listener: $BUDDYBOT_ENABLE_MIC_LISTENER"
echo "[presentation] pi speaker: $BUDDYBOT_ENABLE_PI_SPEAKER"
echo "[presentation] speaker volume: ${BUDDYBOT_SPEAKER_VOLUME_PERCENT}%"
echo "[presentation] camera: ${BUDDYBOT_CAMERA_WIDTH}x${BUDDYBOT_CAMERA_HEIGHT} @ ${BUDDYBOT_CAMERA_FPS}fps publish ${BUDDYBOT_CAMERA_PUBLISH_RATE}Hz format ${BUDDYBOT_CAMERA_PIXEL_FORMAT} discard_buffered ${BUDDYBOT_CAMERA_DISCARD_BUFFERED_FRAMES}"
