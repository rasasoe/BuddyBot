echo "[presentation] detector: interval ${BUDDYBOT_DETECT_INTERVAL}, confidence ${BUDDYBOT_DETECT_CONFIDENCE}, hog_confidence ${BUDDYBOT_DETECT_HOG_CONFIDENCE}, hog_resize ${BUDDYBOT_DETECT_HOG_RESIZE_WIDTH}, hog_fallback ${BUDDYBOT_DETECT_ALLOW_HOG_FALLBACK}, cascade_fallback ${BUDDYBOT_DETECT_ALLOW_CASCADE_FALLBACK}"
echo "[presentation] follow: bbox_timeout ${BUDDYBOT_FOLLOW_BBOX_TIMEOUT}s max_source_age ${BUDDYBOT_FOLLOW_MAX_SOURCE_AGE}s height_gain ${BUDDYBOT_FOLLOW_HEIGHT_GAIN} center_gain ${BUDDYBOT_FOLLOW_CENTER_GAIN} target_height_ratio ${BUDDYBOT_FOLLOW_TARGET_HEIGHT} max_linear ${BUDDYBOT_FOLLOW_MAX_LINEAR} min_linear ${BUDDYBOT_FOLLOW_MIN_LINEAR} max_angular ${BUDDYBOT_FOLLOW_MAX_ANGULAR} deadzone ${BUDDYBOT_FOLLOW_CENTER_DEADZONE}/${BUDDYBOT_FOLLOW_HEIGHT_DEADZONE} rate ${BUDDYBOT_FOLLOW_COMMAND_RATE}Hz accel ${BUDDYBOT_FOLLOW_LINEAR_ACCEL}/${BUDDYBOT_FOLLOW_ANGULAR_ACCEL} bbox_alpha ${BUDDYBOT_FOLLOW_BBOX_SMOOTHING_ALPHA} allow_reverse ${BUDDYBOT_FOLLOW_ALLOW_REVERSE}"

exec bash "$ROOT_DIR/scripts/run_demo_debug_bundle.sh" "$MODE"
